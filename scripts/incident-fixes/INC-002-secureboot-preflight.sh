#!/usr/bin/env bash
set -euo pipefail

echo "== Secure-Boot-Status =="
mokutil --sb-state 2>&1 || true

echo "== Enrolled MOK-Schluessel =="
mokutil --list-enrolled 2>/dev/null | grep -c 'Subject:' || true

echo "== DKMS-Module =="
if command -v dkms >/dev/null; then
  dkms status 2>&1 || true
else
  echo "dkms nicht installiert"
fi

echo "== Module ausserhalb von kernel/ (installiert, nicht nur geladen) und Signatur =="
found=0
while IFS= read -r f; do
  found=1
  s="$(modinfo -F signer "$f" 2>/dev/null || true)"
  echo "$(basename "$f")  $f  signer=${s:-UNSIGNIERT}"
done < <(find "/lib/modules/$(uname -r)" -type f \( -name '*.ko' -o -name '*.ko.*' \) -not -path '*/kernel/*' 2>/dev/null | sort)
(( found )) || echo "keine"

echo "== Module unter kernel/ mit fremdem Signierer (z. B. nvidia, vmmon, vmnet) =="
while IFS= read -r f; do
  s="$(modinfo -F signer "$f" 2>/dev/null || true)"
  [[ -n "$s" ]] || s="UNSIGNIERT"
  case "$s" in
    "Build time autogenerated kernel key"|Canonical*|*Ubuntu*) ;;
    *) echo "$(basename "$f")  signer=$s" ;;
  esac
done < <(find "/lib/modules/$(uname -r)" -type f \( -name 'nvidia*.ko*' -o -name 'vmmon*.ko*' -o -name 'vmnet*.ko*' -o -name 'vbox*.ko*' -o -name 'zfs*.ko*' \) 2>/dev/null | sort)

echo "== VMware-Module =="
lsmod | grep -E '^vmw|^vmmon|^vmnet' || echo "keine geladen"

echo "== Ergebnis =="
echo "UNSIGNIERT-Eintraege muessen vor dem Aktivieren von Secure Boot per MOK signiert werden"
